GO
USE QL_CUAHANGXAYDUNG
GO

CREATE TABLE LOAIHANG
(
	MALH NCHAR(10) NOT NULL,
	TENLH NVARCHAR(50),
	CONSTRAINT PK_LOAIHANG PRIMARY KEY (MALH)
)

CREATE TABLE HANGHOA
(
	MAHH NCHAR(10) NOT NULL,
	MALH NCHAR(10) NOT NULL,
	TENHH NVARCHAR(50),
	MOTA NVARCHAR(50),
	HINHSANPHAM NVARCHAR(50),
	SOLUONG INT,
	GIA FLOAT,
	DIACHI NVARCHAR(50),
	XUATXU NVARCHAR(50),
	CONSTRAINT PK_HANGHOA PRIMARY KEY (MAHH),
	CONSTRAINT FK_HANGHOA_LOAIHANG FOREIGN KEY (MALH)  REFERENCES LOAIHANG(MALH)
)

CREATE TABLE NGUOIDUNG
(
	SDT NCHAR(10) NOT NULL,
	TENKH NVARCHAR(50),
	DIACHI NVARCHAR (50),
	MATKHAU nchar(20),
	QUANLY BIT default 0,
	CONSTRAINT PK_NGUOIDUNG PRIMARY KEY (SDT)
)

CREATE TABLE HOADONKH
(
	MAHD NCHAR(15) NOT NULL,
	SDT NCHAR(10) NOT NULL,
	NGAY DATE,
	TONGTIEN FLOAT, 
	TONGSOLUONGSPDAMUA INT,
	CONSTRAINT PK_HOADONKH PRIMARY KEY (MAHD),
	CONSTRAINT FK_HOADONKH_NGUOIDUNG FOREIGN KEY (SDT) REFERENCES NGUOIDUNG(SDT)
)

CREATE TABLE CHITIETHOADONKH
(
	MAHD NCHAR(15) NOT NULL,
	MAHH NCHAR(10) NOT NULL,
	SOLUONG INT,
	CONSTRAINT PK_CHITIETHOADONKH PRIMARY KEY (MAHD, MAHH),
	CONSTRAINT FK_CHITIETHOADONKH_HOADONKH FOREIGN KEY (MAHD) REFERENCES HOADONKH(MAHD),
	CONSTRAINT FK_CHITIETHOADONKH_HANGHOA FOREIGN KEY (MAHH) REFERENCES HANGHOA(MAHH)
)

CREATE TABLE GIAOHANG
(
	MAHD NCHAR(15) NOT NULL,
	DIACHIGIAOHANG NVARCHAR(30),
	TINHTRANG NVARCHAR(30),
	CONSTRAINT PK_GIAOHANG PRIMARY KEY (MAHD),
	CONSTRAINT FK_GIAOHANG_HOADONKH FOREIGN KEY (MAHD) REFERENCES HOADONKH(MAHD),
)

